#!/usr/bin/env python3
"""Build tsd/install_probing_macros.py: a self-contained TSD script that installs this repo's macros.

    python3 tools/build_tsd.py

Every macro is embedded as text with its SHA-256, so one file is all a machine needs. Rebuild and
commit the script whenever a macro changes; tools/test_tsd.py runs it against stub PathPilot modules.
"""
import datetime
import glob
import hashlib
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'tsd', 'install_probing_macros.py')

# Installed set: every probe_*.nc in the repo root (routines and support routines).
OBSOLETE = ['probe_z_for_position.nc']  # moved into the backup folder if present on the machine

TEMPLATE = r'''#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
TSD script: install the CAM driven probing macros into ~/gcode/subroutines.

Generated by tools/build_tsd.py from footpetaljones/PP-Probing-Macros, {version}.
Do not edit by hand: change the macros in the repo and rebuild.

What it does
  1. Stops if a program is running.
  2. Copies any existing versions of these files into
     ~/gcode/subroutines/probing_macros_backup_<date>_<time>/ (obsolete files are moved there).
  3. Writes the {count} macro files and checks each one byte for byte.
  4. Warns if PathPilot's SUBROUTINE_PATH would find another copy of a macro first.
"""
import hashlib
import io
import os
import shutil
import time

import linuxcnc

import diagnostic_script_util
from halsampler_manager import HalSamplerCaptureTool
from diagnostic_script_util import DiagnosticTestBase, DiagnosticError

# Provide a name for the test that will be shown to user before starting it
diagnostic_name = "Install CAM driven probing macros ({version_short})"
log_file_prefix = "probing_macros_install"

# Shown in a dialog when the script first loads, but before it runs
setup_instructions = """
1) Stop any running program (the machine can be on or off)
2) Press OK to install the CAM driven probing macros
"""

# Shown in a dialog when the TSD script starts running
warning_msg = """
The CAM driven probing macros in ~/gcode/subroutines will be replaced.
Existing copies are saved to ~/gcode/subroutines/probing_macros_backup_<date>_<time>.
The machine does not move. Reload any open program afterwards.
"""

# List of pins / signals to sample during the test (nothing is sampled by this script)
tsd_pins = [
    "motion.motion-enabled",
]

MACRO_VERSION = "{version}"
TARGET_DIR = os.path.expanduser("~/gcode/subroutines")
OBSOLETE = {obsolete!r}

# (file name, sha256 of the UTF-8 bytes, contents)
MACROS = [
{macros}]


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def read_bytes(path):
    with io.open(path, "rb") as f:
        return f.read()


def make_dirs(path):
    if not os.path.isdir(path):
        os.makedirs(path)


def subroutine_path():
    """Directories PathPilot searches for subroutines, in order, from the INI file."""
    import redis
    ini_path = redis.Redis().hget("machine_prefs", "linuxcnc_inifilepath")
    if isinstance(ini_path, bytes):
        ini_path = ini_path.decode("utf-8")
    value = linuxcnc.ini(ini_path).find("RS274NGC", "SUBROUTINE_PATH") or ""
    base = os.path.dirname(ini_path)
    dirs = []
    for entry in value.split(":"):
        entry = entry.strip()
        if entry:
            dirs.append(os.path.realpath(os.path.join(base, os.path.expanduser(entry))))
    return dirs


class ProbingMacroInstaller(DiagnosticTestBase):

    def __init__(self):
        DiagnosticTestBase.__init__(self, HalSamplerCaptureTool(), log_file_prefix, tsd_pins)

    def run(self):
        try:
            # Boilerplate to start a new test session (no sampler capture is needed)
            self.start_new_session()
            if self.install():
                self.log("Test Complete")
                self.result_dict["diagnostic_status"] = "complete"
        except Exception as e:
            self.log("Failed: {{}}".format(e))
            raise
        finally:
            self.save_logs()

    def install(self):
        self.log("CAM driven probing macros {{}}".format(MACRO_VERSION))

        # 1. never replace macros while a program is running
        self.stat.poll()
        if self.stat.interp_state != linuxcnc.INTERP_IDLE:
            self.log("Failed: a program is running - stop it and run this script again")
            return False

        # 2. check the embedded copies before touching anything
        for name, digest, text in MACROS:
            if sha256(text.encode("utf-8")) != digest:
                self.log("Failed: embedded copy of {{}} is damaged - nothing was changed".format(name))
                return False

        make_dirs(TARGET_DIR)
        target = os.path.realpath(TARGET_DIR)

        # 3. back up what is there
        stamp = time.strftime("%Y%m%d_%H%M%S")
        backup_dir = os.path.join(TARGET_DIR, "probing_macros_backup_" + stamp)
        backed_up = []
        unchanged = []
        for name, digest, text in MACROS:
            path = os.path.join(TARGET_DIR, name)
            if os.path.isfile(path):
                if sha256(read_bytes(path)) == digest:
                    unchanged.append(name)
                    continue
                make_dirs(backup_dir)
                shutil.copy2(path, os.path.join(backup_dir, name))
                backed_up.append(name)
        moved = []
        for name in OBSOLETE:
            path = os.path.join(TARGET_DIR, name)
            if os.path.isfile(path):
                make_dirs(backup_dir)
                shutil.move(path, os.path.join(backup_dir, name))
                moved.append(name)

        # 4. write each file through a temporary name, then rename it into place
        written = []
        for name, digest, text in MACROS:
            if name in unchanged:
                continue
            path = os.path.join(TARGET_DIR, name)
            temp = path + ".tsd_tmp"
            with io.open(temp, "wb") as f:
                f.write(text.encode("utf-8"))
            os.chmod(temp, 0o644)
            os.rename(temp, path)
            written.append(name)

        # 5. verify every installed file
        bad = [name for name, digest, text in MACROS
               if sha256(read_bytes(os.path.join(TARGET_DIR, name))) != digest]

        # 6. which copy will PathPilot use?
        warnings = []
        try:
            dirs = subroutine_path()
            if target not in dirs:
                warnings.append("{{}} is not in SUBROUTINE_PATH ({{}}) - PathPilot will not find these macros".format(
                    TARGET_DIR, ":".join(dirs)))
            else:
                earlier = dirs[:dirs.index(target)]
                for name, digest, text in MACROS:
                    for d in earlier:
                        if os.path.isfile(os.path.join(d, name)):
                            warnings.append("PathPilot will use {{}} instead of the new {{}}".format(
                                os.path.join(d, name), name))
                            break
        except Exception as e:
            warnings.append("could not read SUBROUTINE_PATH ({{}}) - check that {{}} is searched".format(e, TARGET_DIR))

        # 7. report
        self.log("Installed in {{}}: {{}} written, {{}} already up to date".format(
            TARGET_DIR, len(written), len(unchanged)))
        for name in written:
            self.log("  wrote {{}}".format(name))
        if backed_up or moved:
            self.log("Previous versions saved in {{}}".format(backup_dir))
            for name in backed_up:
                self.log("  saved {{}}".format(name))
            for name in moved:
                self.log("  removed obsolete {{}} (moved to the backup folder)".format(name))
        for w in warnings:
            self.log("WARNING: " + w)
        if bad:
            self.log("Failed: these files did not verify: {{}}".format(", ".join(bad)))
            return False
        return True


if __name__ == '__main__':
    tester = ProbingMacroInstaller()
    try:
        tester.run()
    finally:
        tester.on_exit()
'''


def main():
    names = sorted(os.path.basename(p) for p in glob.glob(os.path.join(ROOT, 'probe_*.nc')))
    try:
        commit = subprocess.check_output(['git', '-C', ROOT, 'rev-parse', '--short', 'HEAD']).decode().strip()
    except Exception:
        commit = 'unknown'
    date = datetime.date.today().isoformat()
    entries = []
    for name in names:
        text = open(os.path.join(ROOT, name), encoding='utf-8', newline='').read()
        if '"""' in text or '\\' in text or '\r' in text:
            raise SystemExit('%s contains """, a backslash or CR - cannot embed as a plain literal' % name)
        digest = hashlib.sha256(text.encode('utf-8')).hexdigest()
        entries.append('    ("%s", "%s", u"""%s"""),\n' % (name, digest, text))
    version = 'commit %s, built %s' % (commit, date)
    script = TEMPLATE.format(version=version, version_short='%s %s' % (date, commit), count=len(names),
                             obsolete=OBSOLETE, macros=''.join(entries))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(script)
    print('wrote %s: %d macros, %s' % (os.path.relpath(OUT, ROOT), len(names), version))


if __name__ == '__main__':
    main()
