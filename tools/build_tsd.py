#!/usr/bin/env python3
"""Build the two TSD scripts that put a macro set on a machine.

    python3 tools/build_tsd.py

  tsd/install_probing_macros.py           the macros in this repo (probe_*.nc)
  tsd/restore_original_probing_macros.py  the original macros (commit ORIGINAL_COMMIT)

Each macro is embedded as text with its SHA-256, so one file is all a machine needs. Each script
moves the other set's extra files out of the way, so install and restore undo each other. Rebuild
and commit whenever a macro changes; tools/test_tsd.py runs both against stub PathPilot modules.
"""
import hashlib
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSD_DIR = os.path.join(ROOT, 'tsd')

# The production macro set before this work (Norman's upload); the restore script writes these.
ORIGINAL_COMMIT = '9fe40cb'

TEMPLATE = r'''#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""
TSD script: @SUMMARY@

Generated by tools/build_tsd.py from footpetaljones/PP-Probing-Macros (@SET_LABEL@).
Do not edit by hand: change the macros in the repo and rebuild.

What it does
  1. Stops if a program is running, or if ~/tmc/subroutines is missing or read-only.
  2. Saves the current copy of every file it replaces or removes in
     ~/gcode/probing_macros_backup_<date>_<time>/
  3. Writes the @COUNT@ macro files and checks each one byte for byte.
  4. Removes @REMOVE_TEXT@ if present (a copy is in the backup folder).
  5. Warns if PathPilot's SUBROUTINE_PATH would find another copy of a macro first.
"""
import hashlib
import io
import os
import shutil
import time

import linuxcnc

import diagnostic_script_util
from halsampler_manager import HalSamplerCaptureTool
from diagnostic_script_util import DiagnosticTestBase, DiagnosticError

# Provide a name for the test that will be shown to user before starting it
diagnostic_name = "@NAME@"
log_file_prefix = "@LOG_PREFIX@"

# Shown in a dialog when the script first loads, but before it runs
setup_instructions = """
1) Stop any running program (the machine can be on or off)
2) Press OK to @ACTION@
"""

# Shown in a dialog when the TSD script starts running
warning_msg = """
The CAM driven probing macros in ~/tmc/subroutines will be replaced with the @SET_NAME@.
Replaced and removed files are saved to ~/gcode/probing_macros_backup_<date>_<time>.
The machine does not move. Reload any open program afterwards.
"""

# List of pins / signals to sample during the test (nothing is sampled by this script)
tsd_pins = [
    "motion.motion-enabled",
]

MACRO_SET = "@SET_LABEL@"
TARGET_DIR = os.path.expanduser("~/tmc/subroutines")
BACKUP_PARENT = os.path.expanduser("~/gcode")

# Not part of this set: moved to the backup folder if present
REMOVE = @REMOVE@

# Versions this script recognises, for the log (sha256: label)
KNOWN = {
@KNOWN@}

# (file name, sha256 of the UTF-8 bytes, contents)
MACROS = [
@MACROS@]


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def read_bytes(path):
    with io.open(path, "rb") as f:
        return f.read()


def version_of(path):
    return KNOWN.get(sha256(read_bytes(path)), "other version")


def new_backup_dir():
    base = os.path.join(BACKUP_PARENT, "probing_macros_backup_" + time.strftime("%Y%m%d_%H%M%S"))
    path = base
    n = 2
    while os.path.exists(path):
        path = "{}_{}".format(base, n)
        n += 1
    return path


def subroutine_path():
    """Directories PathPilot searches for subroutines, in order, from the INI file."""
    import redis
    ini_path = redis.Redis().hget("machine_prefs", "linuxcnc_inifilepath")
    if not isinstance(ini_path, str):
        ini_path = ini_path.decode("utf-8")
    value = linuxcnc.ini(ini_path).find("RS274NGC", "SUBROUTINE_PATH") or ""
    base = os.path.dirname(ini_path)
    dirs = []
    for entry in value.split(":"):
        entry = entry.strip()
        if entry:
            dirs.append(os.path.realpath(os.path.join(base, os.path.expanduser(entry))))
    return dirs


class ProbingMacroInstaller(DiagnosticTestBase):

    def __init__(self):
        DiagnosticTestBase.__init__(self, HalSamplerCaptureTool(), log_file_prefix, tsd_pins)

    def run(self):
        try:
            # Boilerplate to start a new test session (no sampler capture is needed)
            self.start_new_session()
            if self.install():
                self.log("Test Complete")
                self.result_dict["diagnostic_status"] = "complete"
        except Exception as e:
            self.log("Failed: {}".format(e))
            raise
        finally:
            self.save_logs()

    def install(self):
        self.log("@LOG_TITLE@: " + MACRO_SET)

        # 1. never replace macros while a program is running
        self.stat.poll()
        if self.stat.interp_state != linuxcnc.INTERP_IDLE:
            self.log("Failed: a program is running - stop it and run this script again")
            return False

        # 2. check the embedded copies and the target folder before touching anything
        for name, digest, text in MACROS:
            if sha256(text.encode("utf-8")) != digest:
                self.log("Failed: embedded copy of {} is damaged - nothing was changed".format(name))
                return False
        if not os.path.isdir(TARGET_DIR):
            self.log("Failed: {} not found - nothing was changed".format(TARGET_DIR))
            return False
        if not os.access(TARGET_DIR, os.W_OK):
            self.log("Failed: {} is read-only - nothing was changed".format(TARGET_DIR))
            return False
        target = os.path.realpath(TARGET_DIR)
        if target != os.path.abspath(TARGET_DIR):
            self.log("{} is {}".format(TARGET_DIR, target))

        # 3. what changes
        writes = []      # (name, digest, text, version replaced or None if new)
        unchanged = []
        for name, digest, text in MACROS:
            path = os.path.join(TARGET_DIR, name)
            if not os.path.isfile(path):
                writes.append((name, digest, text, None))
            elif sha256(read_bytes(path)) == digest:
                unchanged.append(name)
            else:
                writes.append((name, digest, text, version_of(path)))
        removes = [(name, version_of(os.path.join(TARGET_DIR, name)))
                   for name in REMOVE if os.path.isfile(os.path.join(TARGET_DIR, name))]

        # 4. back up everything that will be replaced or removed
        backup_dir = None
        saved = [name for name, digest, text, old in writes if old] + [name for name, old in removes]
        if saved:
            backup_dir = new_backup_dir()
            os.makedirs(backup_dir)
            for name in saved:
                shutil.copy2(os.path.join(TARGET_DIR, name), os.path.join(backup_dir, name))
            missing = [name for name in saved if not os.path.isfile(os.path.join(backup_dir, name))]
            if missing:
                self.log("Failed: could not back up {} - nothing was changed".format(", ".join(missing)))
                return False

        # 5. write each file through a temporary name, then rename it into place
        for name, digest, text, old in writes:
            path = os.path.join(TARGET_DIR, name)
            mode = (os.stat(path).st_mode & 0o777) if old else 0o644
            temp = path + ".tsd_tmp"
            with io.open(temp, "wb") as f:
                f.write(text.encode("utf-8"))
            os.chmod(temp, mode)
            os.rename(temp, path)
        for name, old in removes:
            os.remove(os.path.join(TARGET_DIR, name))

        # 6. verify the result
        bad = [name for name, digest, text in MACROS
               if not os.path.isfile(os.path.join(TARGET_DIR, name)) or
               sha256(read_bytes(os.path.join(TARGET_DIR, name))) != digest]
        bad += [name for name in REMOVE if os.path.exists(os.path.join(TARGET_DIR, name))]

        # 7. which copy will PathPilot use?
        warnings = []
        try:
            dirs = subroutine_path()
            if target not in dirs:
                warnings.append("{} is not in SUBROUTINE_PATH ({}) - PathPilot will not find these macros".format(
                    TARGET_DIR, ":".join(dirs)))
            else:
                earlier = dirs[:dirs.index(target)]
                for name, digest, text in MACROS:
                    for d in earlier:
                        if os.path.isfile(os.path.join(d, name)):
                            warnings.append("PathPilot will use {} instead of {} in {}".format(
                                os.path.join(d, name), name, TARGET_DIR))
                            break
        except Exception as e:
            warnings.append("could not read SUBROUTINE_PATH ({}) - check that {} is searched".format(e, TARGET_DIR))

        # 8. report
        self.log("{}: {} written, {} already up to date, {} removed".format(
            TARGET_DIR, len(writes), len(unchanged), len(removes)))
        for name, digest, text, old in writes:
            if old:
                self.log("  replaced {} ({})".format(name, old))
            else:
                self.log("  added {}".format(name))
        for name, old in removes:
            self.log("  removed {} ({})".format(name, old))
        if backup_dir:
            self.log("Previous copies saved in {}".format(backup_dir))
        for w in warnings:
            self.log("WARNING: " + w)
        if bad:
            self.log("Failed: these files did not verify: {}".format(", ".join(bad)))
            return False
        return True


if __name__ == '__main__':
    tester = ProbingMacroInstaller()
    try:
        tester.run()
    finally:
        tester.on_exit()
'''


def git(*args):
    return subprocess.check_output(['git', '-C', ROOT] + list(args))


def check_embeddable(name, text):
    if '"""' in text or '\\' in text or '\r' in text:
        raise SystemExit('%s contains """, a backslash or CR - cannot embed as a plain literal' % name)


def repo_set():
    names = sorted(f for f in os.listdir(ROOT) if f.startswith('probe_') and f.endswith('.nc'))
    return {n: open(os.path.join(ROOT, n), encoding='utf-8', newline='').read() for n in names}


def commit_set(commit):
    names = git('ls-tree', '--name-only', commit).decode().splitlines()
    names = sorted(n for n in names if n.startswith('probe_') and n.endswith('.nc'))
    return {n: git('show', '%s:%s' % (commit, n)).decode('utf-8') for n in names}


def digest(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def repo_label():
    """Last commit that changed a macro, marked if the working copy differs from it."""
    try:
        commit = git('log', '-1', '--format=%h', '--', 'probe_*.nc').decode().strip()
        dirty = git('status', '--porcelain', '--', 'probe_*.nc').decode().strip()
        return commit + ('+uncommitted' if dirty else '')
    except Exception:
        return 'unknown'


def write_script(filename, macros, remove, known, **words):
    entries = []
    for name in sorted(macros):
        check_embeddable(name, macros[name])
        entries.append('    ("%s", "%s", u"""%s"""),\n' % (name, digest(macros[name]), macros[name]))
    known_lines = ''.join('    "%s": "%s",\n' % (h, label) for h, label in sorted(known.items()))
    words.update(COUNT=str(len(macros)), REMOVE=repr(sorted(remove)), KNOWN=known_lines,
                 REMOVE_TEXT=', '.join(sorted(remove)) or 'nothing')
    script = TEMPLATE
    for key, value in words.items():
        script = script.replace('@%s@' % key, value)
    unfilled = set(re.findall(r'@[A-Z_]+@', script)) - {'@MACROS@'}
    if unfilled:
        raise SystemExit('unfilled placeholder in %s: %s' % (filename, ', '.join(sorted(unfilled))))
    script = script.replace('@MACROS@', ''.join(entries))  # last, so macro text is never substituted into
    path = os.path.join(TSD_DIR, filename)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(script)
    print('wrote tsd/%s: %d macros, removes %s' % (filename, len(macros), ', '.join(sorted(remove)) or 'nothing'))


def main():
    new = repo_set()
    original = commit_set(ORIGINAL_COMMIT)
    label = repo_label()
    # labels for the log; a file that is the same in both sets counts as original
    known = {digest(t): 'new version %s' % label for t in new.values()}
    known.update({digest(t): 'original' for t in original.values()})
    os.makedirs(TSD_DIR, exist_ok=True)

    write_script('install_probing_macros.py', new, set(original) - set(new), known,
                 SUMMARY='install the new CAM driven probing macros into ~/tmc/subroutines.',
                 NAME='Install new CAM driven probing macros (%s)' % label,
                 LOG_PREFIX='probing_macros_install',
                 ACTION='install the new CAM driven probing macros',
                 SET_NAME='new version',
                 SET_LABEL='new macros, commit %s' % label,
                 LOG_TITLE='Installing CAM driven probing macros')

    write_script('restore_original_probing_macros.py', original, set(new) - set(original), known,
                 SUMMARY='put the original CAM driven probing macros back in ~/tmc/subroutines.',
                 NAME='Restore original CAM driven probing macros',
                 LOG_PREFIX='probing_macros_restore',
                 ACTION='restore the original CAM driven probing macros',
                 SET_NAME='original version',
                 SET_LABEL='original macros, commit %s' % ORIGINAL_COMMIT,
                 LOG_TITLE='Restoring CAM driven probing macros')


if __name__ == '__main__':
    main()
